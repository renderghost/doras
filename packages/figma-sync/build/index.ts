// Builds the sync from @doras/tokens' tokens.json:
//   dist/plan.json     the plan, for reading and debugging
//   dist/code.js       the Figma plugin (see manifest.json)
//   dist/use-figma.js  the same, for running through the Figma MCP server
//   dist/use-figma/*   the same, one collection at a time, in order
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
import type { DocTokens } from '../../tokens/build/docs.ts';
import { buildPlan, type Plan } from '../src/plan.ts';

const ROOT = join(import.meta.dirname, '..');
const DIST = join(ROOT, 'dist');
const HEADER = '// Generated by @doras/figma-sync from @doras/tokens. Do not edit.';

/** The applier as plain JavaScript the Figma plugin sandbox can run. */
export function applierJs(): string {
  const source = readFileSync(join(ROOT, 'src', 'apply.ts'), 'utf8');
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: {
      target: ts.ScriptTarget.ES2017,
      module: ts.ModuleKind.ESNext,
      removeComments: false,
      verbatimModuleSyntax: false,
    },
  });
  // A plain script: no imports (types only) and no exports.
  return outputText
    .replace(/^import .*$/gm, '')
    .replace(/^export \{\};?$/gm, '')
    .replace(/^export (async function|function|const)/gm, '$1')
    .trim();
}

const summary = `function summary(r) {
  return 'Doras tokens synced: ' + r.variables.created + ' variables created, ' + r.variables.updated + ' updated, ' +
    (r.textStyles.created + r.textStyles.updated) + ' text styles, ' + (r.effectStyles.created + r.effectStyles.updated) + ' effect styles.' +
    (r.notInTokens.length ? ' ' + r.notInTokens.length + ' variables are no longer in the tokens; they were kept.' : '');
}`;

export function renderPlugin(plan: Plan): string {
  return `${HEADER}
${applierJs()}

${summary}

const PLAN = ${JSON.stringify(plan)};

applyPlan(PLAN, figma).then(
  (report) => figma.closePlugin(summary(report)),
  (error) => figma.closePlugin('Doras token sync failed: ' + (error && error.message ? error.message : String(error))),
);
`;
}

/** For the Figma MCP server's use_figma, which runs a function body with top-level await. */
export function renderUseFigma(plan: Plan): string {
  return `${HEADER}
${applierJs()}

const PLAN = ${JSON.stringify(plan)};

return await applyPlan(PLAN, figma);
`;
}

/**
 * The plan split by collection, in dependency order, for runs too large for
 * one use_figma call. Each style goes with the collection its variables are in.
 */
export function splitPlan(plan: Plan): [string, Plan][] {
  return plan.collections.map((collection, i): [string, Plan] => [
    `${String(i + 1).padStart(2, '0')}-${collection.name.toLowerCase()}`,
    {
      version: 1,
      collections: [collection],
      textStyles: collection.name === 'Typography' ? plan.textStyles : [],
      effectStyles: collection.name === 'Theme' ? plan.effectStyles : [],
    },
  ]);
}

export function readTokens(): DocTokens {
  const require = createRequire(import.meta.url);
  const path = require.resolve('@doras/tokens/tokens.json');
  return JSON.parse(readFileSync(path, 'utf8')) as DocTokens;
}

export function build(): string[] {
  const plan = buildPlan(readTokens());
  mkdirSync(DIST, { recursive: true });
  const files: [string, string][] = [
    ['plan.json', `${JSON.stringify(plan, null, 2)}\n`],
    ['code.js', renderPlugin(plan)],
    ['use-figma.js', renderUseFigma(plan)],
  ];
  for (const [name, part] of splitPlan(plan)) {
    files.push([`use-figma/${name}.js`, renderUseFigma(part)]);
  }
  mkdirSync(join(DIST, 'use-figma'), { recursive: true });
  for (const [name, content] of files) writeFileSync(join(DIST, name), content);
  return files.map(([name]) => name);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = build();
  console.log(`@doras/figma-sync: built ${files.join(', ')} in dist/`);
}
