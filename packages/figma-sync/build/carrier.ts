// Carries payloads into Figma for the MCP route. Figma's upload tool only
// takes images, so each payload travels as an SVG whose <text> lines hold
// its JSON. The loader script reads the text back in Figma and runs the sync.
// Text is ASCII-only with no spaces, so importing the SVG can't change it.

const CHUNK = 3000;
const LINE = 16;

const escapeXml = (s: string): string =>
  s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/** JSON with every non-ASCII character and space escaped, so it survives SVG import. */
export const pack = (value: unknown): string =>
  JSON.stringify(value)
    .replace(/[\u007f-￿]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, '0')}`)
    .replace(/ /g, '\\u0020');

/** An SVG whose text lines carry `value`, each marked @@name#index/count@@. */
export function carrierSvg(name: string, value: unknown): string {
  const body = pack(value);
  const count = Math.ceil(body.length / CHUNK);
  const lines: string[] = [];
  for (let i = 0; i < count; i++) {
    const text = `@@${name}#${i}/${count}@@${body.slice(i * CHUNK, (i + 1) * CHUNK)}`;
    lines.push(
      `<text x="0" y="${(i + 1) * LINE}" font-family="Inter" font-size="10">${escapeXml(text)}</text>`,
    );
  }
  const height = (count + 1) * LINE;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="400" height="${height}" viewBox="0 0 400 ${height}">${lines.join('')}</svg>`;
}

/** Reads a payload back from carrier text lines: what the loader does in Figma. */
export function unpack(name: string, texts: string[]): unknown {
  const marker = new RegExp(`^@@${name}#(\\d+)/(\\d+)@@`);
  const parts: [number, string][] = [];
  let count = 0;
  for (const text of texts) {
    const m = marker.exec(text);
    if (!m) continue;
    count = Number(m[2]);
    parts.push([Number(m[1]), text.slice(m[0].length)]);
  }
  if (parts.length !== count || count === 0) {
    throw new Error(`The ${name} carrier has ${parts.length} of ${count} parts`);
  }
  return JSON.parse(
    parts
      .sort((a, b) => a[0] - b[0])
      .map(([, s]) => s)
      .join(''),
  );
}

/** The page the carriers are uploaded to. */
export const CARRIER_PAGE = '_doras-sync';

/** The use_figma script that reads the carriers, runs the sync and reports. */
export const loaderJs = `// Generated by @doras/figma-sync. Do not edit.
// Upload dist/carrier/*.svg to a page named "${CARRIER_PAGE}" first (see the README).
// Set REMOVE_CARRIERS to true on the last run to delete that page afterwards.
const REMOVE_CARRIERS = false;
const page = figma.root.children.find((p) => p.name === '${CARRIER_PAGE}');
if (!page) throw new Error('No ${CARRIER_PAGE} page: upload the carriers first.');
await page.loadAsync();
const texts = page.findAllWithCriteria({ types: ['TEXT'] }).map((t) => t.characters);
function unpack(name) {
  const marker = new RegExp('^@@' + name + '#(\\\\d+)/(\\\\d+)@@');
  const parts = [];
  let count = 0;
  for (const text of texts) {
    const m = marker.exec(text);
    if (!m) continue;
    count = Number(m[2]);
    parts.push([Number(m[1]), text.slice(m[0].length)]);
  }
  if (parts.length !== count || count === 0) throw new Error('The ' + name + ' carrier has ' + parts.length + ' of ' + count + ' parts');
  return JSON.parse(parts.sort((a, b) => a[0] - b[0]).map((p) => p[1]).join(''));
}
const applyPlan = new Function(unpack('doras-applier') + '\\nreturn applyPlan;')();
const report = await applyPlan(unpack('doras-plan'), figma);
if (REMOVE_CARRIERS) page.remove();
return { ...report, carriersRemoved: REMOVE_CARRIERS };
`;

/**
 * The use_figma script that checks the file against the plan on the carrier
 * page: every variable's type, scopes, code syntax, description and value or
 * alias in every mode, and every style's values and bindings. Read-only.
 */
export const verifyJs = `// Generated by @doras/figma-sync. Do not edit. Read-only.
const page = figma.root.children.find((p) => p.name === '${CARRIER_PAGE}');
if (!page) throw new Error('No ${CARRIER_PAGE} page: upload the carriers first.');
await page.loadAsync();
const texts = page.findAllWithCriteria({ types: ['TEXT'] }).map((t) => t.characters);
function unpack(name) {
  const marker = new RegExp('^@@' + name + '#(\\\\d+)/(\\\\d+)@@');
  const parts = [];
  let count = 0;
  for (const text of texts) {
    const m = marker.exec(text);
    if (!m) continue;
    count = Number(m[2]);
    parts.push([Number(m[1]), text.slice(m[0].length)]);
  }
  if (parts.length !== count || count === 0) throw new Error('The ' + name + ' carrier has ' + parts.length + ' of ' + count + ' parts');
  return JSON.parse(parts.sort((a, b) => a[0] - b[0]).map((p) => p[1]).join(''));
}
const plan = unpack('doras-plan');
const problems = [];
const collections = await figma.variables.getLocalVariableCollectionsAsync();
const variables = await figma.variables.getLocalVariablesAsync();
const byId = new Map(variables.map((v) => [v.id, v]));
const collectionName = new Map(collections.map((c) => [c.id, c.name]));
// Figma stores numbers as 32-bit floats, so 0.9765 comes back as 0.97649997.
const close = (a, b) => typeof a === 'number' && typeof b === 'number' && Math.abs(a - b) < 0.0005;
const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);
let checked = 0;
for (const pc of plan.collections) {
  const c = collections.find((x) => x.name === pc.name);
  if (!c) { problems.push('Missing collection ' + pc.name); continue; }
  if (!same(c.modes.map((m) => m.name), pc.modes)) problems.push(pc.name + ' modes are ' + c.modes.map((m) => m.name).join(', '));
  if (c.hiddenFromPublishing !== pc.hiddenFromPublishing) problems.push(pc.name + ' hiddenFromPublishing is ' + c.hiddenFromPublishing);
  for (const pv of pc.variables) {
    const v = variables.find((x) => x.variableCollectionId === c.id && x.name === pv.name);
    const where = pc.name + '/' + pv.name;
    if (!v) { problems.push('Missing ' + where); continue; }
    checked++;
    if (v.resolvedType !== pv.type) problems.push(where + ' is ' + v.resolvedType);
    if (!same([...v.scopes].sort(), [...pv.scopes].sort())) problems.push(where + ' scopes ' + v.scopes.join(','));
    if (v.description !== pv.description) problems.push(where + ' description differs');
    for (const p of ['WEB', 'iOS', 'ANDROID']) if ((v.codeSyntax[p] || undefined) !== pv.codeSyntax[p]) problems.push(where + ' ' + p + ' code syntax is ' + v.codeSyntax[p]);
    for (const m of c.modes) {
      const want = pv.values[m.name];
      const got = v.valuesByMode[m.modeId];
      if (want && typeof want === 'object' && 'alias' in want) {
        const target = got && got.type === 'VARIABLE_ALIAS' ? byId.get(got.id) : undefined;
        const name = target ? collectionName.get(target.variableCollectionId) + '/' + target.name : String(got && got.type);
        if (name !== want.alias.collection + '/' + want.alias.name) problems.push(where + ' ' + m.name + ' aliases ' + name);
      } else if (want && typeof want === 'object' && 'r' in want) {
        if (!got || !['r', 'g', 'b', 'a'].every((k) => close(got[k], want[k]))) problems.push(where + ' ' + m.name + ' colour is ' + JSON.stringify(got));
      } else if (want && typeof want === 'object' && 'fontFamilies' in want) {
        if (typeof got !== 'string' || (want.fontFamilies.indexOf(got) < 0 && got !== want.fallback)) problems.push(where + ' family is ' + got);
      } else if (typeof want === 'number' ? !close(got, want) : got !== want) {
        problems.push(where + ' ' + m.name + ' is ' + JSON.stringify(got) + ', not ' + JSON.stringify(want));
      }
    }
  }
}
const textStyles = await figma.getLocalTextStylesAsync();
for (const ts of plan.textStyles) {
  const s = textStyles.find((x) => x.name === ts.name);
  if (!s) { problems.push('Missing text style ' + ts.name); continue; }
  if (!close(s.fontSize, ts.fontSize)) problems.push(ts.name + ' font size ' + s.fontSize);
  if (!s.lineHeight || !close(s.lineHeight.value, ts.lineHeight)) problems.push(ts.name + ' line height');
  for (const f of ['fontFamily', 'fontSize', 'lineHeight', 'letterSpacing']) {
    const b = s.boundVariables && s.boundVariables[f];
    const target = b ? byId.get(b.id) : undefined;
    const want = ts.bindings[f];
    if (!target || target.name !== want.name || collectionName.get(target.variableCollectionId) !== want.collection) problems.push(ts.name + ' ' + f + ' is not bound to ' + want.name);
  }
}
const effectStyles = await figma.getLocalEffectStylesAsync();
for (const es of plan.effectStyles) {
  const s = effectStyles.find((x) => x.name === es.name);
  if (!s) { problems.push('Missing effect style ' + es.name); continue; }
  if (s.effects.length !== es.layers.length) problems.push(es.name + ' has ' + s.effects.length + ' layers');
  s.effects.forEach((e, i) => {
    const b = e.boundVariables && e.boundVariables.color;
    const target = b ? byId.get(b.id) : undefined;
    if (!target || target.name !== es.layers[i].colorVariable.name) problems.push(es.name + ' layer ' + (i + 1) + ' colour is not bound');
  });
}
const allScopes = variables.filter((v) => v.scopes.indexOf('ALL_SCOPES') >= 0).map((v) => v.name);
return {
  ok: problems.length === 0 && allScopes.length === 0,
  checked,
  planned: plan.collections.reduce((n, c) => n + c.variables.length, 0),
  textStyles: plan.textStyles.length,
  effectStyles: plan.effectStyles.length,
  allScopes,
  problems: problems.slice(0, 40),
  problemCount: problems.length,
};
`;
