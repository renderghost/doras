// Writes tokens.json for documentation and the Figma sync, and a small typed
// entry point that maps token names to CSS custom properties.
import { cssDeclarations, cssName, isPublic } from './css.ts';
import type { ResolvedToken, Tier } from './resolve.ts';
import { aliasOf } from './values.ts';

export interface DocToken {
  name: string;
  tier: Tier;
  type: string;
  description: string | null;
  /** The CSS custom property, or null for primitives, which never reach CSS. */
  cssVar: string | null;
  /** The Windows forced-colours system colour, for colours that have one. */
  forcedColor: string | null;
  /** For each theme: the resolved value, its CSS, and the token it refers to, if any. */
  values: Record<string, { value: unknown; css: string | null; aliasOf: string | null }>;
}

export interface DocTokens {
  themes: string[];
  defaultTheme: string;
  tokens: DocToken[];
}

export function renderDocs(
  themes: Map<string, ResolvedToken[]>,
  defaultTheme = 'light',
): DocTokens {
  const names = [...themes.keys()];
  const maps = new Map(
    names.map((t) => [t, new Map((themes.get(t) ?? []).map((x) => [x.name, x]))]),
  );
  const base = themes.get(defaultTheme) ?? [];
  const tokens = base.map((token): DocToken => {
    const values: DocToken['values'] = {};
    for (const theme of names) {
      const map = maps.get(theme) ?? new Map<string, ResolvedToken>();
      const t = map.get(token.name);
      if (!t) throw new Error(`${token.name} is missing from ${theme}`);
      const css = isPublic(t)
        ? cssDeclarations(t, map)
            .map(([n, v]) =>
              n === cssName(t.path) ? v : `${n.slice(cssName(t.path).length + 1)}: ${v}`,
            )
            .join('; ')
        : null;
      values[theme] = { value: t.value, css, aliasOf: aliasOf(t.original) ?? null };
    }
    const forced = (token.extensions?.['org.doras'] as { forcedColor?: string } | undefined)
      ?.forcedColor;
    return {
      name: token.name,
      tier: token.tier,
      type: token.type,
      description: token.description ?? null,
      cssVar: isPublic(token) ? cssName(token.path) : null,
      forcedColor: forced ?? null,
      values,
    };
  });
  return { themes: names, defaultTheme, tokens };
}

/** index.js and index.d.ts: token names, their CSS custom properties and the themes. */
export function renderEntry(docs: DocTokens): { js: string; dts: string } {
  const publicTokens = docs.tokens.filter((t) => t.cssVar !== null);
  const vars = Object.fromEntries(publicTokens.map((t) => [t.name, t.cssVar]));
  const js = `// Generated by @doras/tokens. Do not edit.
export const themes = ${JSON.stringify(docs.themes)};
export const defaultTheme = ${JSON.stringify(docs.defaultTheme)};
export const cssVars = Object.freeze(${JSON.stringify(vars, null, 2)});
/** The CSS var() for a token, such as var(--doras-color-text-default). */
export const cssVar = (name) => \`var(\${cssVars[name]})\`;
`;
  const union = publicTokens.map((t) => `  | '${t.name}'`).join('\n');
  const dts = `// Generated by @doras/tokens. Do not edit.
export type DorasTheme = ${docs.themes.map((t) => `'${t}'`).join(' | ')};
/** Every token that components may use: semantic and component tokens. */
export type DorasToken =
${union};
export declare const themes: readonly DorasTheme[];
export declare const defaultTheme: DorasTheme;
export declare const cssVars: Readonly<Record<DorasToken, \`--doras-\${string}\`>>;
/** The CSS var() for a token, such as var(--doras-color-text-default). */
export declare function cssVar(name: DorasToken): string;
`;
  return { js, dts };
}
