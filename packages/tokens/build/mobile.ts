// Writes the tokens for iOS (Swift) and Android (Kotlin). Each platform gets
// a dependency-free core file and a small adapter for its UI framework.
// Dimensions are numbers: points on iOS, dp on Android (sp for type).
import { isPublic } from './css.ts';
import type { ResolvedToken } from './resolve.ts';
import {
  camel,
  cubicBezier,
  ms,
  pascal,
  px,
  rgba,
  shadowLayers,
  textStyle,
  type Rgba,
  type ShadowLayer,
} from './values.ts';

export const KOTLIN_PACKAGE = 'io.github.renderghost.doras.tokens';
const HEADER = 'Generated by @doras/tokens from src/doras.resolver.json. Do not edit.';

/** Namespaces for the first part of a token's path. Avoids clashes such as Swift's "Type". */
const NAMESPACES: Record<string, string> = {
  color: 'Colors',
  shadow: 'Shadows',
  type: 'Typography',
};

interface Member {
  namespace: string;
  name: string;
  token: string;
  description: string | undefined;
  /** One value per theme, in theme order. */
  values: ResolvedToken[];
}

/** Groups public tokens by namespace, with each theme's value side by side. */
export function members(themes: Map<string, ResolvedToken[]>): Member[] {
  const order = [...themes.keys()];
  const first = themes.get(order[0] ?? '') ?? [];
  const lookup = order.map((t) => new Map((themes.get(t) ?? []).map((x) => [x.name, x])));
  return first.filter(isPublic).map((token) => {
    const path = token.tier === 'component' ? token.path.slice(1) : token.path;
    const [head = '', ...rest] = path;
    return {
      namespace: NAMESPACES[head] ?? pascal([head]),
      name: camel(rest),
      token: token.name,
      description: token.description,
      values: lookup.map((map) => {
        const v = map.get(token.name);
        if (!v) throw new Error(`${token.name} is missing from a theme`);
        return v;
      }),
    };
  });
}

const num = (n: number): string => {
  const s = String(Math.round(n * 10000) / 10000);
  return s.includes('.') ? s : `${s}.0`;
};

const groupBy = (list: Member[]): Map<string, Member[]> => {
  const map = new Map<string, Member[]>();
  for (const m of list) map.set(m.namespace, [...(map.get(m.namespace) ?? []), m]);
  return map;
};

// ---------------------------------------------------------------- Swift

const SWIFT_KEYWORDS = new Set(
  'associatedtype class deinit enum extension fileprivate func import init inout internal let open operator private protocol public rethrows static struct subscript typealias var break case continue default defer do else fallthrough for guard if in repeat return switch where while as Any catch false is nil super self Self throw throws true try Type'.split(
    ' ',
  ),
);
const swiftName = (n: string): string => (SWIFT_KEYWORDS.has(n) ? `\`${n}\`` : n);

const swiftRgba = (c: Rgba): string =>
  `DorasRGBA(red: ${num(c.r)}, green: ${num(c.g)}, blue: ${num(c.b)}, alpha: ${num(c.a)})`;
const swiftShadow = (layers: ShadowLayer[]): string =>
  `[${layers
    .map(
      (l) =>
        `DorasShadowLayer(color: ${swiftRgba(l.color)}, x: ${num(l.x)}, y: ${num(l.y)}, blur: ${num(l.blur)}, spread: ${num(l.spread)})`,
    )
    .join(', ')}]`;
const swiftThemed = (type: string, items: string[], themes: string[]): string =>
  `${type}(${themes.map((t, i) => `${t}: ${items[i]}`).join(', ')})`;

function swiftValue(m: Member, themes: string[]): [string, string] {
  const [first] = m.values;
  if (!first) throw new Error(`No value for ${m.token}`);
  switch (first.type) {
    case 'color':
      return [
        'DorasThemedColor',
        swiftThemed(
          'DorasThemedColor',
          m.values.map((v) => swiftRgba(rgba(v.value))),
          themes,
        ),
      ];
    case 'shadow':
      return [
        'DorasThemedShadow',
        swiftThemed(
          'DorasThemedShadow',
          m.values.map((v) => swiftShadow(shadowLayers(v.value))),
          themes,
        ),
      ];
    case 'dimension':
      return ['Double', num(px(first.value))];
    case 'duration':
      return ['TimeInterval', num(ms(first.value) / 1000)];
    case 'cubicBezier': {
      const [x1, y1, x2, y2] = cubicBezier(first.value);
      return [
        'DorasEasing',
        `DorasEasing(x1: ${num(x1)}, y1: ${num(y1)}, x2: ${num(x2)}, y2: ${num(y2)})`,
      ];
    }
    case 'typography': {
      const t = textStyle(first.value);
      return [
        'DorasTextStyle',
        `DorasTextStyle(fontFamily: [${t.fontFamily.map((f) => JSON.stringify(f)).join(', ')}], fontSize: ${num(t.fontSize)}, fontWeight: ${t.fontWeight}, lineHeight: ${num(t.lineHeight)}, letterSpacing: ${num(t.letterSpacing)})`,
      ];
    }
    default:
      throw new Error(`No Swift format for ${first.type} (${m.token})`);
  }
}

export function renderSwift(themes: Map<string, ResolvedToken[]>): {
  core: string;
  swiftui: string;
} {
  const names = [...themes.keys()];
  const all = members(themes);
  const enums = [...groupBy(all)].map(([namespace, list]) => {
    const lines = list.flatMap((m) => {
      const [type, value] = swiftValue(m, names);
      return [
        ...(m.description ? [`    /// ${m.description}`] : []),
        `    /// Token: \`${m.token}\``,
        `    public static let ${swiftName(m.name)}: ${type} = ${value}`,
      ];
    });
    return `  public enum ${namespace} {\n${lines.join('\n')}\n  }`;
  });
  const cases = names.map((n) => `  case ${n}`).join('\n');
  const themedField = (type: string): string =>
    names.map((n) => `  public let ${n}: ${type}`).join('\n');
  const switchOn = names.map((n) => `    case .${n}: return ${n}`).join('\n');
  const core = `// ${HEADER}
// Dimensions are in points. Colours are sRGB, from 0 to 1.

import Foundation

/// The four Doras themes. High contrast builds on light or dark.
public enum DorasTheme: String, CaseIterable, Sendable {
${cases}
}

public struct DorasRGBA: Equatable, Sendable {
  public let red: Double
  public let green: Double
  public let blue: Double
  public let alpha: Double
}

/// A colour with a value for every theme.
public struct DorasThemedColor: Equatable, Sendable {
${themedField('DorasRGBA')}

  public func resolve(_ theme: DorasTheme) -> DorasRGBA {
    switch theme {
${switchOn}
    }
  }
}

public struct DorasShadowLayer: Equatable, Sendable {
  public let color: DorasRGBA
  public let x: Double
  public let y: Double
  public let blur: Double
  public let spread: Double
}

/// A shadow, made of layers, for every theme.
public struct DorasThemedShadow: Equatable, Sendable {
${themedField('[DorasShadowLayer]')}

  public func resolve(_ theme: DorasTheme) -> [DorasShadowLayer] {
    switch theme {
${switchOn}
    }
  }
}

public struct DorasTextStyle: Equatable, Sendable {
  public let fontFamily: [String]
  /// In points.
  public let fontSize: Double
  public let fontWeight: Int
  /// A multiple of the font size.
  public let lineHeight: Double
  /// In points.
  public let letterSpacing: Double
}

/// A cubic Bézier easing curve.
public struct DorasEasing: Equatable, Sendable {
  public let x1: Double
  public let y1: Double
  public let x2: Double
  public let y2: Double
}

public enum DorasTokens {
${enums.join('\n\n')}
}
`;
  const swiftui = `// ${HEADER}
// SwiftUI helpers for the Doras tokens.

#if canImport(SwiftUI)
import SwiftUI

public extension DorasTheme {
  /// The Doras theme for SwiftUI's colour scheme and contrast settings.
  init(colorScheme: ColorScheme, contrast: ColorSchemeContrast) {
    switch (colorScheme, contrast) {
    case (.dark, .increased): self = .darkHighContrast
    case (.dark, _): self = .dark
    case (_, .increased): self = .lightHighContrast
    default: self = .light
    }
  }
}

public extension DorasRGBA {
  var color: Color { Color(.sRGB, red: red, green: green, blue: blue, opacity: alpha) }
}

public extension DorasThemedColor {
  func color(_ theme: DorasTheme) -> Color { resolve(theme).color }
}

public extension DorasTextStyle {
  /// The font weight SwiftUI has nearest to this style's weight.
  var swiftUIWeight: Font.Weight {
    switch fontWeight {
    case ..<150: return .ultraLight
    case ..<250: return .thin
    case ..<350: return .light
    case ..<450: return .regular
    case ..<550: return .medium
    case ..<650: return .semibold
    case ..<750: return .bold
    case ..<850: return .heavy
    default: return .black
    }
  }
}
#endif
`;
  return { core, swiftui };
}

// ---------------------------------------------------------------- Kotlin

const KOTLIN_KEYWORDS = new Set(
  'as break class continue do else false for fun if in interface is null object package return super this throw true try typealias typeof val var when while'.split(
    ' ',
  ),
);
const kotlinName = (n: string): string => (KOTLIN_KEYWORDS.has(n) ? `\`${n}\`` : n);
const kf = (n: number): string => `${num(n)}f`;
const kotlinRgba = (c: Rgba): string => `DorasRgba(${kf(c.r)}, ${kf(c.g)}, ${kf(c.b)}, ${kf(c.a)})`;
const kotlinShadow = (layers: ShadowLayer[]): string =>
  `listOf(${layers
    .map(
      (l) =>
        `DorasShadowLayer(${kotlinRgba(l.color)}, ${kf(l.x)}, ${kf(l.y)}, ${kf(l.blur)}, ${kf(l.spread)})`,
    )
    .join(', ')})`;
const kotlinThemed = (type: string, items: string[], themes: string[]): string =>
  `${type}(${themes.map((t, i) => `${t} = ${items[i]}`).join(', ')})`;

function kotlinValue(
  m: Member,
  themes: string[],
): { decl: 'const val' | 'val'; type: string; value: string } {
  const [first] = m.values;
  if (!first) throw new Error(`No value for ${m.token}`);
  switch (first.type) {
    case 'color':
      return {
        decl: 'val',
        type: 'DorasThemedColor',
        value: kotlinThemed(
          'DorasThemedColor',
          m.values.map((v) => kotlinRgba(rgba(v.value))),
          themes,
        ),
      };
    case 'shadow':
      return {
        decl: 'val',
        type: 'DorasThemedShadow',
        value: kotlinThemed(
          'DorasThemedShadow',
          m.values.map((v) => kotlinShadow(shadowLayers(v.value))),
          themes,
        ),
      };
    case 'dimension':
      return { decl: 'const val', type: 'Float', value: kf(px(first.value)) };
    case 'duration':
      return { decl: 'const val', type: 'Long', value: `${Math.round(ms(first.value))}L` };
    case 'cubicBezier': {
      const [x1, y1, x2, y2] = cubicBezier(first.value);
      return {
        decl: 'val',
        type: 'DorasEasing',
        value: `DorasEasing(${kf(x1)}, ${kf(y1)}, ${kf(x2)}, ${kf(y2)})`,
      };
    }
    case 'typography': {
      const t = textStyle(first.value);
      return {
        decl: 'val',
        type: 'DorasTextStyle',
        value: `DorasTextStyle(listOf(${t.fontFamily.map((f) => JSON.stringify(f)).join(', ')}), ${kf(t.fontSize)}, ${t.fontWeight}, ${kf(t.lineHeight)}, ${kf(t.letterSpacing)})`,
      };
    }
    default:
      throw new Error(`No Kotlin format for ${first.type} (${m.token})`);
  }
}

export function renderKotlin(themes: Map<string, ResolvedToken[]>): {
  core: string;
  compose: string;
} {
  const names = [...themes.keys()];
  const enumNames = names.map((n) => pascal([n]));
  const all = members(themes);
  const objects = [...groupBy(all)].map(([namespace, list]) => {
    const lines = list.flatMap((m) => {
      const { decl, type, value } = kotlinValue(m, names);
      return [
        `    /** ${m.description ? `${m.description} ` : ''}Token: \`${m.token}\` */`,
        `    ${decl} ${kotlinName(m.name)}: ${type} = ${value}`,
      ];
    });
    return `  object ${namespace} {\n${lines.join('\n')}\n  }`;
  });
  const themedClass = (
    cls: string,
    type: string,
  ): string => `/** ${cls === 'DorasThemedColor' ? 'A colour' : 'A shadow, made of layers,'} for every theme. */
data class ${cls}(
${names.map((n) => `  val ${n}: ${type},`).join('\n')}
) {
  fun resolve(theme: DorasTheme): ${type} = when (theme) {
${names.map((n, i) => `    DorasTheme.${enumNames[i]} -> ${n}`).join('\n')}
  }
}`;
  const core = `// ${HEADER}
// Dimensions are in dp, and type sizes in sp. Colours are sRGB, from 0 to 1.

package ${KOTLIN_PACKAGE}

/** The four Doras themes. High contrast builds on light or dark. */
enum class DorasTheme { ${enumNames.join(', ')} }

data class DorasRgba(val red: Float, val green: Float, val blue: Float, val alpha: Float)

${themedClass('DorasThemedColor', 'DorasRgba')}

data class DorasShadowLayer(val color: DorasRgba, val x: Float, val y: Float, val blur: Float, val spread: Float)

${themedClass('DorasThemedShadow', 'List<DorasShadowLayer>')}

/** A text style. Sizes and letter spacing in sp; line height is a multiple of the font size. */
data class DorasTextStyle(
  val fontFamily: List<String>,
  val fontSize: Float,
  val fontWeight: Int,
  val lineHeight: Float,
  val letterSpacing: Float,
)

/** A cubic Bézier easing curve. */
data class DorasEasing(val x1: Float, val y1: Float, val x2: Float, val y2: Float)

object DorasTokens {
${objects.join('\n\n')}
}
`;
  const compose = `// ${HEADER}
// Jetpack Compose helpers for the Doras tokens.

package ${KOTLIN_PACKAGE}.compose

import androidx.compose.animation.core.CubicBezierEasing
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.text.TextStyle
import androidx.compose.ui.text.font.FontFamily
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp
import ${KOTLIN_PACKAGE}.DorasEasing
import ${KOTLIN_PACKAGE}.DorasRgba
import ${KOTLIN_PACKAGE}.DorasTextStyle
import ${KOTLIN_PACKAGE}.DorasTheme
import ${KOTLIN_PACKAGE}.DorasThemedColor

/** The Doras theme for the system's dark theme and contrast settings. */
fun dorasTheme(isDark: Boolean, highContrast: Boolean): DorasTheme = when {
  isDark && highContrast -> DorasTheme.DarkHighContrast
  isDark -> DorasTheme.Dark
  highContrast -> DorasTheme.LightHighContrast
  else -> DorasTheme.Light
}

fun DorasRgba.toColor(): Color = Color(red, green, blue, alpha)

fun DorasThemedColor.color(theme: DorasTheme): Color = resolve(theme).toColor()

/** A token dimension as Dp. */
val Float.dorasDp: Dp get() = this.dp

fun DorasEasing.toEasing(): CubicBezierEasing = CubicBezierEasing(x1, y1, x2, y2)

/** The Compose text style. Apps supply the font family they've loaded. */
fun DorasTextStyle.toTextStyle(fontFamily: FontFamily = FontFamily.Default): TextStyle = TextStyle(
  fontFamily = fontFamily,
  fontSize = this.fontSize.sp,
  fontWeight = FontWeight(fontWeight),
  lineHeight = (this.fontSize * lineHeight).sp,
  letterSpacing = letterSpacing.sp,
)
`;
  return { core, compose };
}
