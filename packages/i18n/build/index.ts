// Checks the catalogues, makes the pseudo-locale, and writes the compiled
// catalogues: a TypeScript module for the runtime, and JSON for other tools.
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { readCatalogues, readNaughtyList } from './catalogues.ts';
import { checkCatalogues, checkNaughtyList } from './check.ts';
import { pseudoLocalise } from './pseudo.ts';

export function compile(): Record<string, Record<string, string>> {
  const { source, translations } = readCatalogues();
  const problems = [
    ...checkCatalogues(source, translations),
    ...checkNaughtyList(source, readNaughtyList()),
  ];
  if (problems.length) {
    throw new Error(
      `The message catalogues have ${problems.length} problem(s):\n- ${problems.join('\n- ')}`,
    );
  }
  const keys = Object.keys(source.messages).sort();
  const sourceMessages = Object.fromEntries(
    keys.map((k) => [k, source.messages[k]?.message ?? '']),
  );
  const compiled: Record<string, Record<string, string>> = {
    'en-GB': sourceMessages,
    'en-XA': Object.fromEntries(keys.map((k) => [k, pseudoLocalise(sourceMessages[k] ?? '')])),
  };
  for (const t of translations) {
    compiled[t.locale] = Object.fromEntries(keys.map((k) => [k, t.messages[k] ?? '']));
  }
  return compiled;
}

function build(): void {
  const compiled = compile();
  const keys = Object.keys(compiled['en-GB'] ?? {});

  const generated = fileURLToPath(new URL('../src/generated/', import.meta.url));
  mkdirSync(generated, { recursive: true });
  writeFileSync(
    `${generated}catalogues.ts`,
    [
      '// Generated by build/index.ts from src/messages. Do not edit.',
      "import type { Locale } from '../locales.ts';",
      '',
      '/** Every message key, from the UK English source. */',
      `export type MessageKey =\n${keys.map((k) => `  | ${JSON.stringify(k)}`).join('\n')};`,
      '',
      `export const catalogues: Record<Locale, Record<MessageKey, string>> = ${JSON.stringify(compiled, null, 2)};`,
      '',
    ].join('\n'),
  );

  const out = fileURLToPath(new URL('../dist/catalogues/', import.meta.url));
  mkdirSync(out, { recursive: true });
  for (const [locale, messages] of Object.entries(compiled)) {
    writeFileSync(`${out}${locale}.json`, `${JSON.stringify(messages, null, 2)}\n`);
  }
  console.log(`Compiled ${keys.length} messages in ${Object.keys(compiled).length} locales.`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) build();
