// Writes the specs package's JavaScript and types from the specs.
import { compile } from 'json-schema-to-typescript';
import { readFileSync } from 'node:fs';
import { COMPONENT_SCHEMA, type MeasurementEvent, type Spec } from './specs.ts';

const pascal = (s: string): string =>
  s
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join('');

const doc = (text: string, indent = ''): string =>
  `${indent}/** ${text.replace(/\*\//g, '*\\/')} */\n`;

interface FullSpec extends Spec {
  summary: string;
  props: (Spec['props'][number] & { description: string; required?: boolean })[];
  events: (Spec['events'][number] & {
    when: string;
    detail?: Record<string, { type: string; description: string }>;
  })[];
}

function propType(prop: FullSpec['props'][number]): string {
  if (prop.type === 'enum')
    return (prop.values ?? []).map((v) => JSON.stringify(v.value)).join(' | ');
  // A list's items are typed by the component itself.
  if (prop.type === 'list') return 'unknown[]';
  return prop.type;
}

/** A component's props and events, as TypeScript, for its Lit class to implement. */
export function componentTypes(spec: FullSpec): string {
  const name = `Doras${pascal(spec.name)}`;
  const props = spec.props
    .map((p) => {
      const optional = p.default === undefined && !p.required ? '?' : '';
      const fallback = p.default === undefined ? '' : ` Defaults to ${JSON.stringify(p.default)}.`;
      return `${doc(`${p.description}${fallback}`, '  ')}  ${p.name}${optional}: ${propType(p)};`;
    })
    .join('\n');
  const events = spec.events
    .filter((e) => e.kind === 'ui' && e.name.startsWith('doras-'))
    .map((e) => {
      const detail = e.detail
        ? `{ ${Object.entries(e.detail)
            .map(([k, v]) => `${k}: ${v.type}`)
            .join('; ')} }`
        : 'undefined';
      return `${doc(e.when, '  ')}  ${JSON.stringify(e.name)}: CustomEvent<${detail}>;`;
    })
    .join('\n');
  return [
    `${doc(`${spec.name}: the props its spec defines.`)}export interface ${name}Props {\n${props}\n}`,
    `${doc(`${spec.name}: the custom events it sends.`)}export interface ${name}EventMap {\n${events || '  // None: it sends only native events, such as click.'}\n}`,
  ].join('\n\n');
}

/** The measurement events, as a union of their details. */
export function measurementTypes(events: MeasurementEvent[]): string {
  const members = events.map((e) => {
    const fields = Object.entries(e.carries).map(([k, v]) => {
      const type = v.values
        ? v.values.map((x) => JSON.stringify(x)).join(' | ')
        : v.type === 'integer'
          ? 'number'
          : 'boolean';
      return `${k}: ${type}`;
    });
    return `  | { name: ${JSON.stringify(e.name)}${fields.length ? `; ${fields.join('; ')}` : ''} }`;
  });
  return [
    doc(
      'The detail of a doras-measure event: a measurement event name, and what it carries. Nothing personal.',
    ) + `export type DorasMeasurement =\n${members.join('\n')};`,
    doc('Every measurement event name.') +
      "export type MeasurementEventName = DorasMeasurement['name'];",
    doc('The DOM event components send for measurement events. Apps listen for it on document.') +
      "export declare const MEASURE_EVENT: 'doras-measure';",
    // It bubbles out of shadow roots to the document and window, so all three know it.
    'declare global {\n' +
      ['HTMLElementEventMap', 'DocumentEventMap', 'WindowEventMap']
        .map(
          (map) => `  interface ${map} {\n    'doras-measure': CustomEvent<DorasMeasurement>;\n  }`,
        )
        .join('\n') +
      '\n}',
  ].join('\n\n');
}

/** The ComponentSpec type, generated from the JSON Schema. */
export async function specType(): Promise<string> {
  const schema = JSON.parse(readFileSync(COMPONENT_SCHEMA, 'utf8')) as Parameters<
    typeof compile
  >[0];
  return compile(schema, 'ComponentSpec', {
    bannerComment: '',
    additionalProperties: false,
    ignoreMinAndMaxItems: true,
    format: false,
  });
}

/** dist/index.js and dist/index.d.ts. */
export async function render(
  specs: Map<string, unknown>,
  events: MeasurementEvent[],
): Promise<{ js: string; dts: string }> {
  const keys = [...specs.keys()];
  const js = [
    '// Generated by @doras/specs. Do not edit.',
    `export const specs = ${JSON.stringify(Object.fromEntries(specs), null, 2)};`,
    `export const measurementEvents = ${JSON.stringify(events, null, 2)};`,
    "export const MEASURE_EVENT = 'doras-measure';",
    '',
  ].join('\n\n');
  const dts = [
    '// Generated by @doras/specs from the JSON Schema and the specs. Do not edit.',
    await specType(),
    `export interface MeasurementEvent {\n  name: MeasurementEventName;\n  journey: string;\n  when: string;\n  carries: Record<string, { description: string; values?: string[]; type?: 'boolean' | 'integer' }>;\n}`,
    doc('Every component spec, by file name.') +
      `export declare const specs: {\n${keys.map((k) => `  ${JSON.stringify(k)}: ComponentSpec;`).join('\n')}\n};`,
    doc('The measurement events list.') +
      'export declare const measurementEvents: MeasurementEvent[];',
    measurementTypes(events),
    ...[...specs.values()].map((s) => componentTypes(s as FullSpec)),
    '',
  ].join('\n\n');
  return { js, dts };
}
