// Renders both emails in every locale with sample values, checks each one,
// and writes them out for Storybook (#17). Fails on any problem.
import { mkdirSync, writeFileSync } from 'node:fs';
import { LOCALES } from '@doras/i18n';
import { checkEmail } from '../src/check.ts';
import { renderRecovery, renderWelcome, type Rendered } from '../src/render.ts';

/** Rae, from the flows, recovering with Blacksky; Jo, whose new account Potluck hosts. */
export const SAMPLE_VALUES = {
  recovery: {
    name: 'Rae',
    handle: 'rae.blacksky.app',
    email: 'rae.thompson@example.com',
    app: 'Potluck',
    provider: 'Blacksky',
    code: '482913',
    minutes: 15,
  },
  welcome: {
    name: 'Jo',
    handle: 'jopark.potluck.kitchen',
    email: 'jo.park@example.com',
    app: 'Potluck',
    provider: 'Potluck',
    confirmUrl: 'https://account.potluck.kitchen/confirm?token=8f2a1c',
  },
};

const samples: Record<'recovery' | 'welcome', Record<string, Rendered>> = {
  recovery: {},
  welcome: {},
};
const problems: string[] = [];
mkdirSync('dist/samples', { recursive: true });

for (const locale of LOCALES) {
  const rendered = {
    recovery: await renderRecovery({ locale, ...SAMPLE_VALUES.recovery }),
    welcome: await renderWelcome({ locale, ...SAMPLE_VALUES.welcome }),
  };
  for (const name of ['recovery', 'welcome'] as const) {
    const email = rendered[name];
    const found = checkEmail(email.html, {
      locale,
      links: name === 'recovery' ? 'none' : 'allowed',
    });
    problems.push(...found.map((p) => `${name} (${locale}): ${p}`));
    samples[name][locale] = email;
    writeFileSync(`dist/samples/${name}.${locale}.html`, email.html);
    writeFileSync(`dist/samples/${name}.${locale}.txt`, `${email.text}\n`);
  }
}

writeFileSync(
  'dist/samples.js',
  `// Generated by @doras/emails. Do not edit.\nexport const SAMPLES = ${JSON.stringify(samples)};\n`,
);
writeFileSync(
  'dist/samples.d.ts',
  `// Generated by @doras/emails. Do not edit.
import type { Rendered } from './render.ts';
/** Both emails, rendered in every locale with sample values. */
export declare const SAMPLES: Record<'recovery' | 'welcome', Record<string, Rendered>>;
`,
);

if (problems.length) {
  console.error(`The email check found ${problems.length} problem(s):`);
  for (const p of problems) console.error(`  ${p}`);
  process.exit(1);
}
console.log(`Rendered and checked 2 emails in ${LOCALES.length} locales.`);
